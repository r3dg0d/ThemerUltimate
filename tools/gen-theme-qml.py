#!/usr/bin/env python3
"""Generate qml/Theme.qml (the Quickshell singleton) from tokens.json. Run after adding a token."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
tok = json.loads((root / "tokens.json").read_text())["tokens"]
props = []
for k, v in tok.items():
    name = "void_" if k == "void" else k
    role = v.get("role", "derived: " + " ".join(map(str, v["derive"])) if "derive" in v else "")
    props.append(f'    readonly property color {name}: c("{k}", "{v["nebula"]}")' + (f"   // {role}" if role else ""))
qml = '''pragma Singleton
import QtQuick
import Quickshell
import Quickshell.Io

// ThemerUltimate theme singleton. GENERATED by tools/gen-theme-qml.py from tokens.json; do not edit by hand.
// Reads ~/.config/themer-ultimate/current.json (written by `themer-ultimate apply`) and watches it, so every
// widget restyles live. Fallbacks are the Purple Nebula values, so a missing file looks exactly like the rice.
// https://github.com/r3dg0d/ThemerUltimate
Singleton {
    id: theme
    property var d: ({})
    property int revision: 0                 // bumps on every theme change; Canvas items repaint on it
    readonly property string file: (Quickshell.env("XDG_CONFIG_HOME") || (Quickshell.env("HOME") + "/.config")) + "/themer-ultimate/current.json"

    FileView {
        id: fv
        path: theme.file
        watchChanges: true
        blockLoading: true
        printErrors: false
        onFileChanged: reload()
        onLoaded: theme.load(text())
    }
    function load(s) {
        try { const j = JSON.parse(s); if (j && j.colors) { theme.d = j; theme.revision++ } } catch (e) {}
    }
    Component.onCompleted: load(fv.text())

    function c(k, def) { const v = d.colors ? d.colors[k] : undefined; return v ? v : def }
    function f(k, def) { const v = d.fonts ? d.fonts[k] : undefined; return v ? v : def }
    function g(k, def) { const v = d.glow ? d.glow[k] : undefined; return v !== undefined ? v : def }
    // helpers: alpha variant, "r,g,b" for Canvas rgba() strings, radius scaled by the theme
    function a(col, alpha) { return Qt.rgba(col.r, col.g, col.b, alpha) }
    function rgb(col) { return Math.round(col.r * 255) + "," + Math.round(col.g * 255) + "," + Math.round(col.b * 255) }
    function rgba(col, alpha) { return "rgba(" + rgb(col) + "," + alpha + ")" }
    function r(n) { return Math.round(n * radiusScale) }
    // per-theme icon glyphs (current.json "glyphs"), e.g. glyph("volume-high", Theme.glyph fallback); def when the theme has none
    function glyph(name, def) { const v = d.glyphs ? d.glyphs[name] : undefined; return v ? v : def }

    readonly property string themeId: d.id || "purple-nebula"
    readonly property string name: d.name || "Purple Nebula"
    readonly property bool isLight: (d.mode || "dark") === "light"
    // shape + glow
    readonly property real radiusScale: d.shape && d.shape.radiusScale !== undefined ? d.shape.radiusScale : 1.0
    readonly property real glowNebula: g("nebula", 1.0)   // painted nebula clouds behind widgets
    readonly property real glowStars: g("stars", 1.0)     // star field density
    readonly property real glowRim: g("rim", 1.0)         // lit window rim
    readonly property real glowRain: g("rain", 0.0)       // faint digital-rain glyph columns (H4X0R)
    // fonts
    readonly property string ui: f("ui", "Cellforge")
    readonly property string led: f("led", "Zerodot")
    readonly property string code: f("code", "NullType")
    readonly property string icons: f("icons", "JetBrainsMono Nerd Font")
    // colours
''' + "\n".join(props) + "\n}\n"
(root / "qml/Theme.qml").write_text(qml)
print("wrote qml/Theme.qml with", len(props), "colour tokens")
